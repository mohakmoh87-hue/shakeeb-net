// يسأل المستخدم عند حذف وصل ذي أثر مالي: أولاً تأكيد الحذف، ثم هل يؤثر على المبالغ والتقرير؟
// يُرجع null عند الإلغاء، أو { reverse } حيث:
//   reverse=true  → إرجاع عكسي كامل (السلوك الحالي: المبالغ/الأيام/الكارت/الدين/المخزون).
//   reverse=false → حذف الوصل فقط بلا أي تأثير مالي (يبقى كل شيء كما هو).
export function askVoidEffect(label = "هذا الوصل"): { reverse: boolean } | null {
  if (!window.confirm(`حذف ${label}؟`)) return null;
  const reverse = window.confirm(
    "هل تريد أن يؤثر الحذف على المبالغ والتقرير؟\n\n" +
    "«موافق» = نعم — إرجاع عكسي كامل (المبالغ والأيام والكارت والدين والمخزون).\n" +
    "«إلغاء» = لا — حذف الوصل فقط بلا أي تأثير مالي (تبقى العمليات كما هي).",
  );
  return { reverse };
}
