// ═════ نزعُ الصورة من صفّ الترحيل بعد تنفيذه (طلبُ محمد 2026-08-13) ═════
//
// «الصورُ أحجامُها تضرّ عملي وتُغلي الفاتورة». وصفُّ `wa_relays` كان يحمل نسخةَ base64
// كاملةً لكلّ رسالةٍ **حتى تنظيفِ الخمس دقائق** — فألفُ رسالةٍ بصورةٍ ٣٠٠ ك.ب تعني
// ٤٠٠ ميغابايت تمرّ على القاعدة وتُكتب فيها بلا داعٍ.
//
// 🔑 والصورةُ بعد التنفيذ **بلا فائدةٍ إطلاقاً**: أُرسلت إلى واتساب، والأصلُ محفوظٌ في
//   القالب — فالصفُّ لا يُعاد تنفيذُه أبداً (يُنظَّف بعد خمس دقائق، لا يُستأنَف).
//
// وفي وحدةٍ خالصةٍ بلا تبعيّات لتُختبَر سلوكاً حقيقيّاً لا بمطابقةِ نصٍّ في ملفٍّ ضخم.

/**
 * يُعيد نصَّ `params` بلا الصورة، ويُبقي بقيّةَ الحقول للتشخيص.
 * وأمانُه أوّلاً: عند أيّ تعذُّرٍ (نصٌّ معطوب، بلا صورة) يُعيد النصَّ **كما هو** —
 * فالتنظيفُ مكسبٌ لا واجبٌ يُخاطَر لأجله بفقدِ سجلٍّ تشخيصيّ أو بإفشالِ تحديثِ الحالة.
 */
export function scrubRelayImage(raw: string | null): string | null {
  if (!raw || !raw.includes('"image"')) return raw; // لا صورةَ فيه ⇒ لا مساسَ به
  try {
    const o = JSON.parse(raw) as Record<string, unknown>;
    if (o.image == null) return raw;
    const size = typeof o.image === "string" ? Math.round((o.image.length * 3) / 4 / 1024) : 0;
    o.image = null;
    o.imageSent = `${size}KB`; // أثرٌ صغيرٌ يُخبر التشخيصَ أنّ صورةً أُرسلت وحجمَها
    return JSON.stringify(o);
  } catch {
    return raw;
  }
}
