import { NextResponse } from "next/server";

// ===== منع «المال بلا مكتب» (المرحلة ٣ — قرار محمد 2026-08-04) =====
// كل قوائم المال ونطاقات العزل تسأل «أرني حركات مكاتبي»، فالقيد بلا towerId لا
// يطابق أي مكتب: لا يظهر في المصروفات والمقبوضات، ولا في التقرير اليومي، ولا في
// التقارير — وزرّ الحذف نفسه يرفضه لأنه يتحقق من ملكية المكتب أولاً. أي أن المال
// يُسجَّل ثم يخرج من الوجود بلا أن يراه أحد أو يحذفه أحد.
//
// فحصُ القاعدة يوم 2026-08-04 أثبت أن العدد اليوم **صفر** في كل الجداول (حركات،
// وصولات، فواتير، مشتركون) — فهذه وقاية تمنع تكوّنه لا ترحيلاً لموجود.
export function requireTower(towerId: number | null | undefined, what: string) {
  if (towerId != null) return null;
  return NextResponse.json(
    {
      error:
        `تعذّر تسجيل ${what}: لا مكتب مرتبط بالعملية. ` +
        `القيد بلا مكتب لا يظهر في أي تقرير ولا يمكن حذفه لاحقاً — ` +
        `اربط المشترك أو الفني أو حسابك بمكتب ثم أعد المحاولة.`,
    },
    { status: 400 },
  );
}
