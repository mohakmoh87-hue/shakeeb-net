// ═════ ب-٨ · نافذةُ «يومٍ» بتوقيت بغداد لا بتوقيت الخادم (طلبُ محمد 2026-08-14) ═════
//
// 🔴 **العلّةُ التي تُصلحها هذه الوحدة** — قِيست على الإنتاج: أحدَ عشرَ موضعاً كانت تبني
//   نهايةَ اليوم بـ`d.setHours(23, 59, 59, 999)` على تاريخٍ مُحلَّلٍ من `"YYYY-MM-DD"`.
//   وعمليّةُ الخادم بتوقيت **UTC** ⇒ فصارت نافذةُ «اليوم»:
//     • البدايةُ `T00:00:00Z` = **٠٣:٠٠ بغداد** ⇒ تُفوَّت ٠٠:٠٠–٠٣:٠٠ من ذلك اليوم.
//     • والنهايةُ `T23:59:59Z` = **٠٢:٥٩ بغداد من الغد** ⇒ تُضَمّ ثلاثُ ساعاتٍ من الغد.
//   ⇒ **نافذةٌ مُزاحةٌ +٣ ساعات**، فتُخالف تقاريرُ المدى **التقريرَ اليوميَّ والصندوق**
//     اللذين يستعملان `baghdadDayKey` صحيحاً — فيظهر رقمان مختلفان لليوم نفسِه.
//
// 🎯 والأثرُ مقيسٌ لا مُقدَّر: **٩ قيودٍ ماليّة** تقع في نافذة الخلاف (٠٠:٠٠–٠٣:٠٠ بغداد)
//   بمجموع **٢٨٠٬٠٠٠ د.ع** داخلاً وصفرٍ خارجاً، كلُّها في آخر ٦٠ يوماً من أصل ٣٥٢٩ قيداً.
//
// ✅ **وشرطُ محمد على الإصلاح**: «لا مشكلةَ إذا تغيّر قيدُ يومٍ ما دام **المبلغُ الكلّيُّ
//   يبقى نفسَه ومبلغُ الماستر يبقى نفسَه** في حسابات المدير».
//   وهو محفوظٌ **بنيويّاً لا بالوعد**: هذه الوحدةُ تُبنى بها **حدودُ استعلامٍ** فقط —
//   لا تكتب صفّاً ولا تُعدّل مبلغاً ولا تحذف قيداً. فالمجاميعُ الكلّيّةُ لا تتغيّر
//   رياضيّاً، وإنّما **يُنسَب القيدُ إلى يومه الصحيح**. وحساباتُ المدير والماستر تُحسب
//   في مسارٍ آخرَ لا يستعمل `setHours` أصلاً — فلا يمسّها هذا الإصلاح.
//
// والإزاحةُ ثابتةٌ ٣ ساعاتٍ بلا توقيتٍ صيفيّ — مطابقةً لـ`BAGHDAD_OFFSET_MS` في
// `src/lib/attendance.ts` (والعراقُ لا يُطبّق الصيفيّ).

const BAGHDAD_OFFSET_MS = 3 * 60 * 60 * 1000;

/** هل النصُّ تاريخُ يومٍ خالصٌ `YYYY-MM-DD` (بلا وقت)؟ */
function isDayOnly(s: string): boolean {
  return /^\d{4}-\d{2}-\d{2}$/.test(s.trim());
}

/**
 * بدايةُ اليوم بتوقيت بغداد كلحظةٍ UTC — `YYYY-MM-DDT00:00+03:00`.
 * ويُعيد `null` لنصٍّ غيرِ صالح، فلا يُبنى مدًى من قيمةٍ فاسدة.
 *
 * ⚠️ ونصٌّ يحمل وقتاً صريحاً (ISO كامل) يُترَك كما هو: المتّصلُ حدّد لحظةً بعينها،
 *   وإجبارُها على منتصف الليل يُفسد نيّته.
 */
export function baghdadStart(input: string | null | undefined): Date | null {
  if (!input) return null;
  const s = String(input).trim();
  if (!isDayOnly(s)) {
    const d = new Date(s);
    return isNaN(d.getTime()) ? null : d;
  }
  const midnightUtc = new Date(`${s}T00:00:00.000Z`);
  if (isNaN(midnightUtc.getTime())) return null;
  return new Date(midnightUtc.getTime() - BAGHDAD_OFFSET_MS);
}

/**
 * نهايةُ اليوم بتوقيت بغداد كلحظةٍ UTC — `YYYY-MM-DDT23:59:59.999+03:00`.
 * تُستعمل مع `lte` (كما كان `setHours(23,59,59,999)`) فتبقى دلالةُ «حتى نهاية اليوم».
 */
export function baghdadEnd(input: string | null | undefined): Date | null {
  if (!input) return null;
  const s = String(input).trim();
  if (!isDayOnly(s)) {
    const d = new Date(s);
    return isNaN(d.getTime()) ? null : d;
  }
  const midnightUtc = new Date(`${s}T00:00:00.000Z`);
  if (isNaN(midnightUtc.getTime())) return null;
  // ٢٣:٥٩:٥٩.٩٩٩ بغداد = منتصفُ الليل + ٢٤س − ١مل − ٣س بالـUTC
  return new Date(midnightUtc.getTime() + 86_400_000 - 1 - BAGHDAD_OFFSET_MS);
}
