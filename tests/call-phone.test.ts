import { test, describe } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

// ═════ زرُّ الاتصال: حارسٌ ضدّ عطلٍ صامتٍ وقع فعلاً (بلاغُ محمد 2026-08-19) ═════
//
// طُلب أن يصير رقمُ الهاتف على بطاقة الميدان زرَّ اتصالٍ (رابط `tel:`) بدل نصٍّ يُنسخ.
// ونُشر — ولم يظهر الزرُّ **أبداً**. والسبب:
//
//     const clean = phone.replace(/[^d+]/g, "");     ← الشرطةُ المائلةُ ضاعت
//
// كُتب السطرُ عبر سكربتٍ ابتلع `\d`، فصار المعنى «احذفْ كلَّ ما ليس الحرفَ d أو +»
// ⇒ يمحو **كلَّ أرقام الهاتف** فيصير `clean` فارغاً، فيرتدّ الفرعُ إلى النصّ العاديّ.
//
// 🎯 والدرسُ أنّ العطلَ كان **صامتاً تماماً**: يبني · يمرّ tsc · يمرّ eslint · ويعمل
//    الفرعُ البديل بلا خطأ — ولا يكشفه إلّا عينُ مستخدمٍ ينتظر زرّاً لا يجيء.
//    فالحارسُ هنا يُنفّذ منطقَ التنظيف نفسَه على أرقامٍ حقيقيّة: أيُّ رجوعٍ للعطل
//    (بسكربتٍ آخرَ أو دمجٍ خاطئ) يُسقط الاختبار بدل أن يمرّ صامتاً إلى الإنتاج.

const read = (rel: string) => fs.readFileSync(path.join(process.cwd(), rel), "utf8");
const SRC = "src/app/(app)/field-management/page.tsx";

describe("زرُّ الاتصال على بطاقة الميدان", () => {
  test("🔴 تنظيفُ الرقم يُبقي الأرقامَ — لا يمحوها (العطلُ الذي وقع)", () => {
    const src = read(SRC);
    const m = src.match(/const clean = phone\.replace\(([^,]+), ""\)/);
    assert.ok(m, "لم يُعثَر على سطر تنظيف الرقم في CallPhone");

    // يُبنى التعبيرُ من الكود نفسِه ويُنفَّذ على أرقامٍ حقيقيّة — لا مطابقةَ نصٍّ هشّة
    const re = new RegExp(m![1].trim().replace(/^\//, "").replace(/\/g$/, ""), "g");
    for (const raw of ["07701234567", "0770 123 4567", "+9647701234567", "0770-123-4567"]) {
      const clean = raw.replace(re, "");
      assert.ok(
        clean.length >= 10,
        `تنظيفُ «${raw}» أنتج «${clean}» — الأرقامُ تُمحى فيسقط الزرُّ إلى النصّ العاديّ`,
      );
      assert.ok(/^\+?\d+$/.test(clean), `«${clean}» ليس رقماً صالحاً لـtel:`);
    }
  });

  test("الرقمُ رابطُ tel: يعزل نقرتَه عن فتح البطاقة", () => {
    const src = read(SRC);
    assert.ok(/href=\{`tel:\$\{clean\}`\}/.test(src), "الرقمُ ليس رابطَ tel: — فلا يفتح برامجَ الاتصال");
    // البطاقةُ كلُّها زرُّ فتحٍ: بلا عزلِ النقرة تنفتح النافذةُ بدل الاتصال
    assert.ok(
      /onClick=\{\(e\) => e\.stopPropagation\(\)\}/.test(src),
      "نقرةُ الرقم غيرُ معزولة — ستفتح نافذةَ البطاقة بدل الاتصال",
    );
  });

  test("بطاقةُ أودو يظهر رقمُها أيضاً (هاتفُها في حقلٍ مستقلٍّ لا في الوصف)", () => {
    const src = read(SRC);
    // «من اي مكان وحتى من الاودو» — ووصفُ بطاقة أودو لا يحمل سطرَ «📱 الهاتف»
    const hits = src.match(/faceCallPhone\((?:c|sel)\.description\) \?\? (?:c|sel)\.odooPhone/g) ?? [];
    assert.ok(
      hits.length >= 3,
      `الارتدادُ إلى odooPhone موجودٌ في ${hits.length} مواضعَ فقط — المطلوب: وجهُ البطاقة العاديّ ووجهُ المنجزة والنافذةُ المفتوحة`,
    );
  });
});
