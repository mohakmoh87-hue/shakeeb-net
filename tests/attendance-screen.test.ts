import { test, describe } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

// ═════ أ-١ · شاشةُ «بصمات الحضور» (طلبُ محمد) ═════
//
// بنصّ الطلب: «شاشةٌ تُظهر كلّ فنيّي كلّ المكاتب الذين بصموا اليوم **حصراً**» + «زرّ
// «سجل» يُظهر كلّ الفنيّين، وبالضغط على فنيٍّ تظهر كلّ بصماته».
//
// والخلفيّةُ كانت جاهزةً سلفاً؛ فالحرسُ هنا على ثلاثة أمور تُفسد الشاشةَ بصمت:
//   ١. «حصراً» — لو عُرض غيرُ مَن بصم لَغرِق الجوابُ عن سؤال «مَن عندي اليوم؟».
//   ٢. التوقيت — القيَمُ تأتي UTC؛ وعرضُها بلا منطقةٍ يُظهر بصمةَ ٨ صباحاً كأنّها ٥.
//   ٣. العزل — يجب أن يبقى على الخادم، ولا تُرشِّح الواجهةُ أمناً.

const ROOT = process.cwd();
const read = (rel: string) => fs.readFileSync(path.join(ROOT, rel), "utf8");
const PAGE = "src/app/(app)/attendance/page.tsx";

describe("أ-١ · شاشةُ بصمات الحضور", () => {
  test("الافتراضُ: مَن بصم اليوم حصراً — و«سجل» يُظهر الكلّ", () => {
    const src = read(PAGE);
    assert.match(src, /const stamped = techs\.filter\(\(t\) => t\.state !== "none"\)/, "لا ترشيحَ لمن بصم اليوم");
    // ⚠️ **حُدِّث بالبند ٩**: المعروضُ افتراضاً صار **حضورَ اليوم + كلَّ يومٍ لم يُغلَق**
    //   (طلبُ محمد: «مَن لم يبصم خروجاً حتى الآن فهو لا يزال معلَّقاً مع بصمات أمس»).
    assert.match(src, /const shown = showAll \? techs : \[\.\.\.open, \.\.\.stamped\]/,
      "المعلَّقُ من أمسِ لا يُعرَض مع حضور اليوم");
    assert.match(src, /useState\(false\)/, "«سجل» مفتوحٌ افتراضاً ⇒ يُخالف «حصراً»");
    assert.match(src, /سجل/, "لا زرَّ «سجل»");
  });

  test("بصماتُ فنيٍّ واحدٍ تُجلَب بمُعرّفه من المسار الجاهز", () => {
    const src = read(PAGE);
    // صار الجلبُ بـ`URLSearchParams` ليحمل `from`/`to` للبحث بين تاريخين — والمعرّفُ باقٍ شرطاً
    assert.match(src, /technicianId: String\(techId\)/, "لا جلبَ لسجلّ الفنيّ بمُعرّفه");
    assert.match(src, /attendance\?\$\{q\}/, "لا نداءَ لمسار البصمات");
    assert.match(src, /كلّ بصماته/, "لا زرَّ لعرض بصمات الفنيّ");
  });

  test("🕐 الأوقاتُ تُعرَض بتوقيت بغداد لا بتوقيت الجهاز", () => {
    // القيَمُ تُخزَّن UTC؛ وحاسبةٌ بمنطقةٍ خاطئةٍ (أو خادمٌ UTC) تُظهر البصمةَ منحرفةً
    // ثلاثَ ساعات — فيبدو الحاضرُ متأخّراً والمتأخّرُ منصرفاً.
    const src = read(PAGE);
    assert.match(src, /timeZone: "Asia\/Baghdad"/, "الوقتُ يُعرَض بتوقيت الجهاز لا بغداد");
  });

  test("🔒 العزلُ من الخادم: المسارُ يقصر على مكاتب الوكيل ويرفض مكتبَ غيره", () => {
    const api = read("src/app/api/field/attendance/route.ts");
    assert.match(api, /agentTowerIds\(session\)/, "لا تحديدَ لمكاتب الوكيل");
    assert.match(api, /لا يمكنك عرض حضور مكتب آخر/, "لا رفضَ لمكتبٍ لا يتبع الوكيل");
    // والقائمةُ نفسُها مقصورةٌ على مكاتب الوكيل حين لا يُحدَّد مكتب
    assert.match(api, /towerId: \{ in: agentTowers\.length \? agentTowers : \[-1\] \}/, "قائمةُ الفنيّين غيرُ مقصورةٍ على الوكيل");
    // 🔑 و«لا مكاتبَ» ⇒ `[-1]` لا قائمةٌ فارغة: الفارغةُ في بريزما تعني **بلا شرط** ⇒ كلُّ الفنيّين
    assert.equal(/towerId: \{ in: agentTowers \}/.test(api), false, "قائمةٌ فارغةٌ بلا حارسٍ تُلغي الشرطَ فتكشف الكلّ");
  });

  test("اسمُ المكتب يُرجَع مع كلّ فنيّ — الشاشةُ تجمع كلَّ المكاتب", () => {
    const api = read("src/app/api/field/attendance/route.ts");
    assert.match(api, /office: t\.towerId != null \? \(oNames\.get\(t\.towerId\) \?\? null\) : null/, "لا اسمَ مكتبٍ في الردّ");
    assert.match(read(PAGE), /\{t\.office \?\? "—"\}/, "الشاشةُ لا تعرض المكتب");
  });

  test("الصلاحيّةُ والرابط: الزرُّ موجودٌ والشاشةُ تحرس نفسَها", () => {
    // ⚠️ **حُدِّث بتصحيح محمد**: كنتُ وضعتُ الزرَّ في القائمة الرئيسيّة، وموضعُه
    //   **ترويسةُ صفحة إدارة الفنيين** — «بصمات الفنيين يجب إضافتها في صفحة إدارة
    //   الفنيين في القائمة العلوية». وتلك الصفحةُ بلا شريطٍ جانبيّ أصلاً (`hideSide`)،
    //   فالزرُّ في القائمة الرئيسيّة لا يُرى من حيث يُحتاج.
    const fm = read("src/app/(app)/field-management/page.tsx");
    assert.match(fm, /href="\/attendance"/, "لا زرَّ في ترويسة إدارة الفنيين");
    // البند ٨ · «كلمةٌ واضحةٌ لا صورة · يسارَ دعم مؤقت · وتظهر للمدير فقط»
    assert.match(fm, /canManage && !isTech/, "الزرُّ يظهر للفنيّ — والفنيُّ يبصم ولا يُطالع حضورَ غيره");
    // ⚠️ **حُدِّث 2026-08-14**: طلب محمد أوّلاً «كلمةٌ واضحةٌ لا صورة» (البند ٨)، ثمّ بعد أن
    //   صارت في القائمة المنسدلة طلب «أضِف لها صورةً صغيرةً مثل البقيّة». فالشرطُ الباقي
    //   هو **حضورُ الكلمة**: رمزٌ يسبقها زيادةٌ لا بديل — والمرفوضُ رمزٌ **وحدَه**.
    assert.match(fm, /حضور الفنيين\s*</, "نصُّ الزرّ غائبٌ — رمزٌ وحدَه لا يكفي (البند ٨)");
    assert.match(fm, /🕒 حضور الفنيين/, "الرمزُ الصغيرُ غائبٌ (طلبُ محمد 2026-08-14)");
    // وملاصقاً لـ«دعم مؤقت»: كان «يسارَه» في صفٍّ أفقيّ، وصار **تاليَه** بعد أن جُمعت
    // الأزرارُ في قائمةٍ عاموديّة (البند ١٠). والعلاقةُ محفوظةٌ وإن تغيّر الاتجاه.
    const supAt = fm.indexOf("🤝 دعم مؤقت");
    const btnAt = fm.indexOf('href="/attendance"');
    assert.ok(supAt > -1 && btnAt > supAt && btnAt - supAt < 700, "الزرُّ ليس ملاصقاً لـ«دعم مؤقت»");
    // وداخل مجموعةٍ عنوانُها يخصّ ما فيها (البند ١٠ — «شؤون الفنيّين»)
    assert.match(fm, /<FieldMenu title="شؤون الفنيّين"/, "الأزرارُ ليست في مجموعةٍ معنونة");
    // 🔑 وشارةُ المعلَّقات تصعد إلى عنوان المجموعة — وإلّا صار «المديرُ لم ينتبه» أسوأ
    assert.match(fm, /badge=\{canManage \? leavePending \+ dedPending : 0\}/,
      "شاراتُ المعلَّقات لا تظهر على عنوان المجموعة المطويّة");
    assert.equal(/href: "\/attendance"/.test(read("src/components/shell/AppShell.tsx")), false,
      "الزرُّ ما زال في القائمة الرئيسيّة — وقد طلب محمد نقلَه");
    const src = read(PAGE);
    // حرسُ الصفحة لا يكفيه إخفاءُ الزرّ: العنوانُ يُكتَب مباشرةً
    assert.match(src, /!can\("field\.manage"\) && !can\("field\.payroll"\)/, "الصفحةُ بلا حرسِ صلاحيّة");
  });

  // ═════ توحيدُ الحضور في زرّه المستقلّ (طلبُ محمد 2026-08-14) ═════
  // «يجب نقلُ كلّ شيءٍ إليه… وأيُّ شيءٍ يتعلّق بحضور الفنيّين يجب أن يكون في الزرّ الجديد».
  // فالحرسُ على طرفَي التوحيد معاً: **وصلت** الميزاتُ هنا، و**غادرت** هناك — إذ يكفي
  // أن يعود مكوّنٌ ثانٍ يحمل الخروجَ اليدويَّ ليعود الانقسامُ الذي طلب رفعَه.
  test("🎯 التوحيد · ميزاتُ نافذة إدارة الفنيّين انتقلت إلى الصفحة", () => {
    const src = read(PAGE);
    assert.match(src, /method: "DELETE"|attReq\("DELETE"/, "لا حذفَ لبصمةٍ في الصفحة");
    assert.match(src, /r\.salaryStatementId == null/, "يومٌ مختومٌ بكشفٍ يُعرَض زرُّ حذفِه — والقاعدةُ تمنعه");
    assert.match(src, /بصمةَ خروج|خروجٍ يدويّ|خروج يدوي/, "لا بصمةَ خروجٍ يدويّةٍ في الصفحة");
    assert.match(src, /يومٍ كامل|يوم كامل/, "لا إضافةَ ليومٍ كامل");
    assert.match(src, /setFrom|from"/, "لا بحثَ بين تاريخين");
  });

  test("🚫 التوحيد · لا مكوّنَ حضورٍ ثانٍ خارج الصفحة", () => {
    assert.equal(fs.existsSync(path.join(ROOT, "src/components/AttendanceManager.tsx")), false,
      "نافذةُ الحضور القديمةُ ما زالت قائمةً — فالميزةُ في مكانَين");
    const tm = read("src/components/TechnicianManager.tsx");
    assert.equal(/AttendanceManager/.test(tm), false, "إدارةُ الفنيّين ما زالت تفتح نافذةَ الحضور القديمة");
    // والزرُّ باقٍ لكنّه يقود إلى الصفحة مفتوحةً على الفنيّ — فلا وصولَ يُفقَد
    assert.match(tm, /\/attendance\?tech=\$\{t\.id\}/, "زرُّ «الحضور» لا يقود إلى الصفحة الموحَّدة");
    const page = read(PAGE);
    assert.match(page, /get\("tech"\)/, "الصفحةُ لا تفتح الفنيَّ القادمَ من الزرّ");
    // ومرّةً واحدةً بمرجعٍ: التحديثُ الدوريُّ كلَّ دقيقةٍ كان سيُعيد فتحَ النافذة على وجهه
    assert.match(page, /autoOpened\.current/, "الفتحُ التلقائيُّ بلا حارسٍ — يتكرّر مع كلّ تحديثٍ دوريّ");
    // 🔒 وإخفاءُ الزرّ ليس منعاً: المسارُ نفسُه يرفض حذفَ يومٍ مختومٍ بكشفِ راتب
    const route = read("src/app/api/field/attendance/route.ts");
    assert.match(route, /salaryStatementId: \{ not: null \}/, "المسارُ يحذف يوماً مختوماً بكشفِ راتب");
    // وقراءةُ السجلّ في نافذة الراتب تبقى **عرضاً بلا أفعال** (أ-٧) فلا تُكرَّر الإدارة
    const sal = read("src/components/SalaryModal.tsx");
    assert.equal(/method: "DELETE"|method: "PATCH"/.test(sal), false,
      "نافذةُ الراتب تُعدّل الحضور — والإدارةُ مكانُها زرُّ الحضور وحدَه");
  });
});
